    /// <param name="type">The requested host type.</param>
    /// <param name="location">The request location.</param>
    private sealed class StaticRequest(INamedTypeSymbol type, Location location)
    {
        /// <summary>Gets the requested static host type.</summary>
        public INamedTypeSymbol Type { get; } = type;

        /// <summary>Gets the assembly attribute location.</summary>
        public Location Location { get; } = location;
    }
